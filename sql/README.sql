SQL Analysis

This folder contains SQL queries developed for the AdventureWorks Sales Analysis project.

Topics Covered

* Data exploration and row counting
* Filtering and sorting
* Aggregate functions
* GROUP BY and HAVING
* JOIN operations
* Date-based sales analysis
* Window functions: ROW_NUMBER, RANK, DENSE_RANK, LAG, and LEAD
* Customer and product analysis

Database

AdventureWorks sample database.

Tool

Microsoft SQL Server Management Studio (SSMS)

Purpose

To explore sales data, analyze customer behavior, and identify business insights using SQL.
